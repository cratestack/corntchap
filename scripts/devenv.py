#!/usr/bin/env python3
"""Write .env.dev with random free local ports (so nothing sits on 5432/8080/8081). Used by `just setup`."""
import socket

def free_port():
    with socket.socket() as s:
        s.bind(("127.0.0.1", 0))
        return s.getsockname()[1]

pg, app, kc = free_port(), free_port(), free_port()
print(f"""# Generated by `just setup` (delete to get new ports). Ports are random on purpose.
PG_PORT={pg}
APP_PORT={app}
KC_PORT={kc}
DATABASE_URL=postgres://corn:corn@127.0.0.1:{pg}/corntchap
TEST_DATABASE_ADMIN_URL=postgres://corn:corn@127.0.0.1:{pg}/postgres
BIND=127.0.0.1:{app}
PUBLIC_URL=http://localhost:{app}
# Keycloak dev realm (deploy/dev/keycloak): users admin/admin and dev/dev
OIDC_ISSUER=http://localhost:{kc}/realms/corntchap
OIDC_CLIENT_ID=corntchap
OIDC_CLIENT_SECRET=corntchap-dev-secret""")
