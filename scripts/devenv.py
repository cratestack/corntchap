#!/usr/bin/env python3
"""Write .env.dev with random free local ports (so nothing sits on 5432/8080/8081/9000). Used by `just setup`.

`devenv.py --ensure .env.dev` creates the file, or appends only the keys an older one lacks (keeping its ports).
"""
import socket
import sys


def free_port():
    with socket.socket() as s:
        s.bind(("127.0.0.1", 0))
        return s.getsockname()[1]


def entries(existing):
    pg = existing.get("PG_PORT") or str(free_port())
    app = existing.get("APP_PORT") or str(free_port())
    kc = existing.get("KC_PORT") or str(free_port())
    s3 = existing.get("S3_PORT") or str(free_port())
    return [
        ("PG_PORT", pg),
        ("APP_PORT", app),
        ("KC_PORT", kc),
        ("DATABASE_URL", f"postgres://corn:corn@127.0.0.1:{pg}/corntchap"),
        ("TEST_DATABASE_ADMIN_URL", f"postgres://corn:corn@127.0.0.1:{pg}/postgres"),
        ("BIND", f"127.0.0.1:{app}"),
        ("PUBLIC_URL", f"http://localhost:{app}"),
        ("# Keycloak dev realm (deploy/dev/keycloak): users admin/admin and dev/dev", None),
        ("OIDC_ISSUER", f"http://localhost:{kc}/realms/corntchap"),
        ("OIDC_CLIENT_ID", "corntchap"),
        ("OIDC_CLIENT_SECRET", "corntchap-dev-secret"),
        ("# Files: RustFS (S3-compatible) in compose; dev credentials only", None),
        ("S3_PORT", s3),
        ("S3_ENDPOINT", f"http://127.0.0.1:{s3}"),
        ("S3_BUCKET", "corntchap"),
        ("S3_ACCESS_KEY", "corntchap"),
        ("S3_SECRET_KEY", "corntchap-dev-secret"),
        ("S3_CREATE_BUCKET", "1"),
    ]


def render(pairs):
    return "\n".join(k if v is None else f"{k}={v}" for k, v in pairs)


if len(sys.argv) == 3 and sys.argv[1] == "--ensure":
    path = sys.argv[2]
    try:
        text = open(path).read()
    except FileNotFoundError:
        text = None
    if text is None:
        with open(path, "w") as f:
            f.write("# Generated by `just setup` (delete to get new ports). Ports are random on purpose.\n")
            f.write(render(entries({})) + "\n")
    else:
        existing = {}
        for line in text.splitlines():
            if "=" in line and not line.lstrip().startswith("#"):
                k, v = line.split("=", 1)
                existing[k.strip()] = v.strip()
        missing = [(k, v) for k, v in entries(existing) if v is not None and k not in existing]
        if missing:
            with open(path, "a") as f:
                f.write(("" if text.endswith("\n") else "\n") + "# Added by a newer `just setup`\n")
                f.write(render(missing) + "\n")
            print(f"{path}: added " + ", ".join(k for k, _ in missing))
else:
    print("# Generated by `just setup` (delete to get new ports). Ports are random on purpose.")
    print(render(entries({})))
